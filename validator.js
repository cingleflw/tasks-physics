// Проверка тем и шаблонов задач, присланных из конструктора (constructor.html).
// Конструктор отправляет шаблон в том же формате, что и в файлах tasks/*.json
// (см. «Формат задачи» в README.md). Сервер не доверяет присланным данным: прежде чем
// показать предпросмотр или сохранить шаблон в файл, он проверяет каждое поле
// и пробно создает по шаблону много задач.
// Файл подключается только на сервере (server.js) — так же, как generator.js.

// Берем из генератора задач (generator.js) нужные функции
// const объявляет постоянную: ей один раз присваивается значение, и заново его не присвоить.
// Но если значение — объект или список, менять его содержимое можно: так ниже заполняются copy, params и examples.
// Фигурные скобки после const — «деструктуризация»: из объекта, который вернул require,
// сразу достаются функции с такими же именами, и дальше их можно вызывать просто generateTask(...)
const {
    // generateTask — задача по шаблону, computeValues — значения всех величин задачи,
    // evaluate — значение формулы, formatNumber — число по-русски ("2,5"),
    // fillText — подстановка значений в текст, computeAnswer — округленный правильный ответ
    generateTask, computeValues, evaluate, formatNumber, fillText, computeAnswer
} = require('./generator.js'); // require подключает файл и возвращает его module.exports; './' — та же папка

// Имя величины или поля варианта: латинская буква, затем латинские буквы, цифры и _
// (v, t1, material, ro). Такие имена понимают формулы и подстановки в тексте
// Это регулярное выражение — шаблон для проверки строк, оно записывается между косыми чертами / /.
// По частям: ^ — начало строки; [A-Za-z] — одна латинская буква, большая или маленькая;
// \w* — сколько угодно (* — ноль или больше) латинских букв, цифр и знаков _; $ — конец строки.
// Без ^ и $ подошла бы и строка, где имя — только часть ("1v"). Первым не может быть
// ни цифра (в формуле имя 2v не отличить от числа), ни знак _. Русские буквы \w не считает: "ро" не подойдет
const NAME_PATTERN = /^[A-Za-z]\w*$/;

// Настройки пробной проверки шаблона (см. tryTemplate). Имена из больших букв —
// так принято называть постоянные настройки, которые задаются один раз в начале файла
const TRIAL_COUNT = 1000;       // Сколько пробных задач создать по шаблону
const EXAMPLE_COUNT = 3;        // Сколько из них показать учителю в предпросмотре
const HIDDEN_CHECK_COUNT = 100; // На скольких из них искать скрытый параметр (findHiddenParam):
                                // проверка дольше остальных, а 100 раз хватает с запасом

// Ограничения размера шаблона. По каждому шаблону сервер пробно создает 1000 задач,
// и слишком большой шаблон надолго занял бы сервер: все это время ученики ждали бы
// проверки ответов. Задачам базы хватает с большим запасом (в самой длинной
// 243 знака и 6 подстановок, больше всего — 4 параметра и 9 вариантов)
const MAX_TEXT_LENGTH = 1000;   // Знаков в тексте условия
const MAX_PLACEHOLDERS = 20;    // Подстановок {…} в тексте
const MAX_NAMES = 10;           // Случайных параметров (и отдельно — вычисляемых величин)
const MAX_FORMULA_LENGTH = 200; // Знаков в формуле
const MAX_CHOICES = 50;         // Вариантов у одного параметра
const MAX_FIELD_LENGTH = 100;   // Знаков в текстовом поле варианта ("меди")

// Сообщает об ошибке в присланных данных: создает ошибку и бросает ее (throw).
// throw сразу прерывает проверку, а server.js по status = 400 («неверный запрос»)
// понимает, что текст ошибки написан для учителя и его можно показать
// (так же main.js различает ошибки по error.status)
// function объявляет функцию: fail — ее имя, message — параметр (текст, который передают при вызове)
function fail(message) {
    const error = new Error(message); // new Error создает объект ошибки, текст хранится в error.message
    error.status = 400;               // Отметка: ошибка в присланных данных, а не в самом сервере
    // Ошибку перехватит catch в handleRequest (server.js) и отправит ее текст браузеру с кодом 400
    throw error;
}

// Объект вида { ... }: не null (typeof null тоже равно 'object') и не массив
function isObject(value) {
    // typeof возвращает тип значения строкой: 'number', 'string', 'object'... У массива тоже 'object',
    // поэтому массивы отсеивает !Array.isArray (! — «не»). && — «и»: нужны все три условия сразу;
    // === и !== — строгое «равно» и «не равно». Такая же проверка есть в readJSON (server.js)
    // null — особое значение «ничего»; return возвращает результат (true или false) тому, кто вызвал isObject
    return typeof value === 'object' && value !== null && !Array.isArray(value);
}

// Проверяет имя величины. what — кто носит это имя, для текста ошибки: "Параметр", "Величина"
function checkName(name, what) {
    // test проверяет, подходит ли строка под шаблон, и возвращает true или false
    if (!NAME_PATTERN.test(name)) {
        // Строка в обратных кавычках `...` — шаблонная: вместо ${what} и ${name} подставляются
        // их значения. Получится, например: Параметр «1v»: имя должно начинаться с латинской буквы...
        fail(`${what} «${name}»: имя должно начинаться с латинской буквы, дальше — латинские буквы, цифры и _`);
    }
}

// Проверяет, что значение — непустая строка, и возвращает ее без пробелов по краям.
// message — текст ошибки, если строки нет
function checkText(value, message) {
    // trim() убирает пробелы и переводы строк по краям: "  Па " → "Па". || — «или»: ошибка,
    // если прислана не строка или строка из одних пробелов. Тип проверяется первым: у числа
    // или undefined нет trim, а если левая часть || верна, правая уже не вычисляется
    if (typeof value !== 'string' || value.trim() === '') {
        fail(message); // Например, «Введите текст условия»
    }
    return value.trim(); // return возвращает результат тому, кто вызвал функцию
}

// Проверяет формулу: в ней могут быть только числа, имена величин, знаки + - * / и скобки.
// generator.js тоже проверяет формулу, но уже после подстановки чисел и пропускает
// записи, которые JavaScript понимает по-своему: "v // t" — это v и комментарий
// (ответ вышел бы просто v), "v ** 2" — возведение в степень, а число с нулем
// впереди, 010, — это 8 (запись в восьмеричной системе).
// what — название формулы для текста ошибки, например "Формула ответа"
function checkFormula(formula, what) {
    // Формула должна быть непустой строкой; text — она же без пробелов по краям
    const text = checkText(formula, `${what}: формула не заполнена`);
    // length — длина строки в знаках
    if (text.length > MAX_FORMULA_LENGTH) {
        fail(`${what}: формула должна быть не длиннее ${MAX_FORMULA_LENGTH} знаков`);
    }
    // Все знаки формулы — из разрешенного списка. [ ... ] — один любой знак из перечисленных:
    // \w — латинская буква, цифра или _; \s — пробел (а также табуляция и перевод строки);
    // точка (0.5, material.ro); + - * / и скобки. Минус записан как \-, потому что внутри [ ]
    // знак - означает диапазон, как в A-Z. * после ] — сколько угодно таких знаков подряд,
    // ^ и $ — от начала до конца строки. Запятая, ^, %, = и русские буквы не пройдут
    // (запятую в числах "9,8" конструктор сам заменяет точкой еще в браузере)
    if (!/^[\w\s.+\-*/()]*$/.test(text)) {
        fail(`${what}: можно использовать только числа, имена величин, знаки + - * / и скобки`);
    }
    // Запрещенные сочетания знаков: | — «или»; \* — сам знак * (без \ он значил бы «сколько угодно»);
    // \/ — сам знак / (без \ косая черта закончила бы само регулярное выражение; внутри [ ], как
    // в проверке выше, \ перед / не нужна). Ищется ** (степень), а также // или /* (начало комментария).
    // ^ и $ здесь нет: сочетание ищется в любом месте формулы
    if (/\*\*|\/\/|\/\*/.test(text)) {
        fail(`${what}: недопустимое сочетание знаков **, // или /*`);
    }
    // Ноль, за которым идет цифра, в начале числа: перед нулем нет ни буквы, ни цифры, ни точки.
    // Так 010 и (07) находятся, а 10, 0.5, 1.05 и имя t05 — нет
    // По частям: (^|[^\w.]) — один из двух вариантов (| — «или»): начало строки или знак, который не \w и не точка
    // (^ сразу после [ означает «кроме»): пробел, скобка, знак действия; 0 — сам ноль;
    // \d — любая цифра от 0 до 9 сразу за ним. Например, в "3 - 05" найдется " 05"
    if (/(^|[^\w.])0\d/.test(text)) {
        fail(`${what}: число не может начинаться с нуля — пишите 10, а не 010`);
    }
    return text; // Проверенная формула без пробелов по краям — ее и запишем в шаблон
}

// Проверяет один вариант из списка choices: это число (2.7) или объект,
// у которого поля — числа или строки ({ "name": "меди", "ro": 8.9 }).
// Возвращает копию варианта.
// Number.isFinite отсеивает не только строки, но и бесконечность: JSON.parse('1e999')
// дает Infinity, а в файл Infinity записалось бы как null
function checkVariant(name, variant) {
    // Вариант — конечное число (например, 2.7): проверять больше нечего, возвращаем его как есть
    if (Number.isFinite(variant)) {
        return variant; // return сразу завершает функцию: проверки ниже — только для объектов
    }
    // Иначе нужен объект хотя бы с одним полем. Object.keys — список имен полей объекта:
    // { name: "меди", ro: 8.9 } → ["name", "ro"], а length — длина этого списка
    if (!isObject(variant) || Object.keys(variant).length === 0) {
        // Пример — в той же записи, в какой учитель вводит вариант в поле конструктора
        fail(`Параметр «${name}»: вариант должен быть числом или набором полей, например name: меди; ro: 8,9`);
    }

    const copy = {}; // Копия варианта, собранная из проверенных полей
    // for...of перебирает список по одному элементу. Object.entries превращает объект в список пар
    // [имя поля, значение]: { name: "меди", ro: 8.9 } → [["name", "меди"], ["ro", 8.9]],
    // а [field, value] раскладывает каждую пару на две переменные (тоже деструктуризация)
    for (const [field, value] of Object.entries(variant)) {
        // Имя поля — по тем же правилам, что имя величины: в тексте и формулах оно пишется
        // через точку — {material.name}, material.ro
        checkName(field, `Параметр «${name}», поле`);
        // Текст — только непустая строка, не из одних пробелов. Число с единицами ("8,9 г/см³") —
        // тоже текст: если такое поле стоит в формуле, ошибку найдет пробная проверка (evaluate в generator.js)
        const isText = typeof value === 'string' && value.trim() !== '';
        // Значение поля — конечное число или такой текст; true, null, списки и объекты не подходят
        if (!Number.isFinite(value) && !isText) {
            fail(`Параметр «${name}», поле «${field}»: значение должно быть числом или текстом`);
        }
        // Текст поля подставляется в условие, поэтому его длина ограничена (MAX_FIELD_LENGTH)
        if (isText && value.length > MAX_FIELD_LENGTH) {
            fail(`Параметр «${name}», поле «${field}»: текст должен быть не длиннее ${MAX_FIELD_LENGTH} знаков`);
        }
        copy[field] = value; // copy[field] — поле, имя которого лежит в переменной field: copy.ro = 8.9
    }
    return copy; // Например, { name: "меди", ro: 8.9 }
}

// Проверяет описание одного случайного параметра и возвращает его копию,
// в которую попадают только нужные поля:
//   { "min": 1, "max": 5, "step": 0.5 } — число из диапазона (шаг можно не указывать)
//   { "choices": [ ... ] }              — один из вариантов
function checkParam(name, spec) {
    checkName(name, 'Параметр'); // Имя параметра, например v или material
    // Описание параметра должно быть объектом { ... }
    if (!isObject(spec)) {
        fail(`Параметр «${name}» описан неверно`);
    }

    // Список вариантов
    // undefined — «значение не задано»: если поля choices нет, это диапазон чисел (ниже)
    if (spec.choices !== undefined) {
        // Нужен список (массив) хотя бы из одного варианта: из пустого списка нечего выбрать
        if (!Array.isArray(spec.choices) || spec.choices.length === 0) {
            fail(`Параметр «${name}»: добавьте хотя бы один вариант`);
        }
        // И не слишком длинный (MAX_CHOICES)
        if (spec.choices.length > MAX_CHOICES) {
            fail(`Параметр «${name}»: вариантов должно быть не больше ${MAX_CHOICES}`);
        }
        // map проверяет каждый вариант и собирает новый массив из их копий
        // (variant) => checkVariant(name, variant) — стрелочная функция, короткая запись функции:
        // получает вариант и возвращает результат checkVariant. Ошибка в любом варианте прервет map.
        // В копию попадает только поле choices, остальные поля описания (например, min) отбрасываются
        return { choices: spec.choices.map((variant) => checkVariant(name, variant)) };
    }

    // Диапазон чисел
    // Нужны конечные числа min («от») и max («до»): строка "5" или отсутствующее поле не подойдут
    if (!Number.isFinite(spec.min) || !Number.isFinite(spec.max)) {
        fail(`Параметр «${name}»: укажите числа «от» и «до»`);
    }
    // При «от» больше «до» generator.js выбирал бы числа неправильно (например, при «от» 5 и «до» 1 — только 2, 3 и 4)
    if (spec.min > spec.max) {
        fail(`Параметр «${name}»: число «от» больше, чем «до»`);
    }

    const range = { min: spec.min, max: spec.max }; // Копия только с нужными полями: { min: 1, max: 5 }
    // Шаг необязателен: если его нет, generator.js берет шаг 1
    if (spec.step !== undefined) {
        // generator.js делит длину диапазона на шаг: при шаге 0 числа не получилось бы вовсе (NaN —
        // «не число»), а при отрицательном шаге числа выбирались бы неправильно
        if (!Number.isFinite(spec.step) || spec.step <= 0) {
            fail(`Параметр «${name}»: шаг должен быть числом больше нуля`);
        }
        range.step = spec.step; // Шаг попадает в копию, только если его указали
    }
    return range; // Например, { min: 40, max: 120, step: 10 }
}

// Проверяет новую тему: { "id": "7_pressure", "grade": 7, "title": "Давление" }.
// Возвращает тему, в которой пока нет задач
// Эту функцию вызывает handleCreateTopic в server.js (POST /api/topics — кнопка «Создать тему» в конструкторе).
// Что data — объект, уже проверил readJSON в server.js
function checkTopic(data) {
    // includes проверяет, есть ли значение в списке. Строка "7" не подойдет — нужно число
    // [6, 7, 8] — список (массив) классов, для которых составлен тест; ! — «не»: ошибка, если класса в нем нет
    if (![6, 7, 8].includes(data.grade)) {
        fail('Класс должен быть 6, 7 или 8');
    }

    const title = checkText(data.title, 'Введите название темы'); // Название без пробелов по краям
    // Название показывается в списках тем на страницах теста и конструктора — ограничим его длину
    if (title.length > 100) {
        fail('Название темы должно быть не длиннее 100 знаков');
    }

    // id — имя файла темы: "7_pressure" → tasks/7_pressure.json. Начинается с номера
    // класса и знака _, как у тем базы, дальше — латинские буквы, цифры и _
    // (\w в JavaScript — это именно они; так же имя темы проверяет loadTopic в server.js)
    const prefix = `${data.grade}_`; // Начало имени, например "7_"
    // Условия через && проверяются по порядку и до первого неверного: id — строка (у числа нет
    // startsWith), начинается (startsWith) с prefix, а остаток после prefix — от 1 до 50 знаков \w
    // ({1,50} — «от 1 до 50 раз»). Поэтому в имени не окажется / или .. — с ними можно было бы
    // записать файл вне папки tasks
    const isGoodId = typeof data.id === 'string' && data.id.startsWith(prefix)
        && /^\w{1,50}$/.test(data.id.slice(prefix.length)); // slice отрезает начало: "7_pressure" → "pressure"
    if (!isGoodId) {
        fail(`Имя файла должно начинаться с «${prefix}», дальше — от 1 до 50 латинских букв, цифр и _, например ${prefix}pressure`);
    }

    // Тема без задач: ее запишет в файл tasks/<id>.json функция saveTopic в server.js
    return { id: data.id, grade: data.grade, title: title, tasks: [] };
}

// Проверяет шаблон задачи и возвращает его «чистую» копию: только поля из README
// в том же порядке, что и в файлах tasks/*.json. Номера шаблона (id) здесь нет —
// его назначает сервер при сохранении
// Эту функцию вызывают handlePreview (кнопка «Предпросмотр») и handleSaveTemplate (кнопка «Сохранить задачу»)
// в server.js; data — поле task из запроса
function checkTemplate(data) {
    // Поля task нет в запросе или это не объект — проверять нечего
    if (!isObject(data)) {
        fail('Неверный запрос');
    }

    const text = checkText(data.text, 'Введите текст условия'); // Текст условия без пробелов по краям
    if (text.length > MAX_TEXT_LENGTH) { // Зачем нужны ограничения размера — см. MAX_TEXT_LENGTH в начале файла
        fail(`Текст условия должен быть не длиннее ${MAX_TEXT_LENGTH} знаков`);
    }
    // Подстановки записываются в фигурных скобках: {v}. Уберем из текста все подстановки:
    // если скобки еще остались, у какой-то скобки нет пары, и ученик увидел бы ее в условии
    // Регулярное выражение /\{[^{}]+\}/g по частям: \{ и \} — сами фигурные скобки (без \ у них особый
    // смысл); [^{}]+ — один или больше (+) любых знаков, кроме { и }; g — найти все подстановки, а не
    // только первую. replace заменяет каждую найденную подстановку пустой строкой: "{s} км за {t} ч" → " км за  ч".
    // /[{}]/ — в остатке есть хотя бы одна { или }: так находятся "{v", "v}" и пустые скобки "{}"
    if (/[{}]/.test(text.replace(/\{[^{}]+\}/g, ''))) {
        fail('В тексте условия есть фигурная скобка без пары. Величина записывается так: {v}');
    }
    // match находит все подстановки; если их нет, он возвращает null — тогда берем пустой список
    // "{s} км за {t} ч" → ["{s}", "{t}"]. ?? — «если слева null или undefined, взять то, что справа»
    if ((text.match(/\{[^{}]+\}/g) ?? []).length > MAX_PLACEHOLDERS) {
        fail(`В тексте условия должно быть не больше ${MAX_PLACEHOLDERS} подстановок {…}`);
    }

    // params — объект { имя: описание }; без случайных параметров все задачи были бы одинаковыми
    if (!isObject(data.params) || Object.keys(data.params).length === 0) {
        fail('Добавьте хотя бы один случайный параметр');
    }
    if (Object.keys(data.params).length > MAX_NAMES) {
        fail(`Случайных параметров должно быть не больше ${MAX_NAMES}`);
    }
    const params = {}; // Проверенные копии параметров: { v: { min: 40, max: 120, step: 10 }, ... }
    // Каждую пару [имя, описание] проверяет checkParam; ошибка в любом параметре прервет проверку
    for (const [name, spec] of Object.entries(data.params)) {
        params[name] = checkParam(name, spec);
    }

    // Вычисляемые величины необязательны. Порядок сохраняется:
    // generator.js считает их по очереди, и каждая может использовать предыдущие
    const derived = {}; // Проверенные формулы: { s: "v * t" }
    if (data.derived !== undefined) { // Конструктор не присылает derived, если величин нет
        if (!isObject(data.derived)) {
            fail('Вычисляемые величины описаны неверно');
        }
        if (Object.keys(data.derived).length > MAX_NAMES) {
            fail(`Вычисляемых величин должно быть не больше ${MAX_NAMES}`);
        }
        // Пары [имя величины, формула], например ["s", "v * t"]
        for (const [name, formula] of Object.entries(data.derived)) {
            checkName(name, 'Величина'); // Имя — по тем же правилам, что у параметров: s, F, m2
            // Object.hasOwn — есть ли уже параметр с таким именем
            // (только среди полей самого params, без встроенных вроде toString). Иначе computeValues
            // в generator.js молча заменил бы случайное значение параметра вычисленным
            if (Object.hasOwn(params, name)) {
                fail(`Величина «${name}» уже есть среди случайных параметров`);
            }
            // Формула проверяется здесь, а считается уже в пробных задачах (tryTemplate)
            derived[name] = checkFormula(formula, `Формула величины «${name}»`);
        }
    }

    // Собираем шаблон по порядку полей, как в файлах базы
    // Поля объекта идут в том порядке, в каком их добавили, — так они и запишутся в файл темы
    const template = { text: text, params: params };
    if (Object.keys(derived).length > 0) {
        template.derived = derived; // Нет вычисляемых величин — нет и поля derived
    }
    template.answer = checkFormula(data.answer, 'Формула ответа');            // Например, "s / t"
    template.unit = checkText(data.unit, 'Укажите единицу измерения ответа'); // Например, "км/ч" или "Па"

    // Точность необязательна: если ее нет, ответ округляется до 2 знаков (getPrecision в generator.js)
    if (data.precision !== undefined) {
        // Number.isInteger — целое ли число: 2 — да, 2.5 и строка "2" — нет. precision — количество знаков
        // после запятой (README), поэтому оно целое и не меньше 0: при дробной точности computeAnswer
        // в generator.js округлял бы ответ до странных чисел (при 1.5: 2.3456 → 2.3400854685246006).
        // 6 знаков — с запасом для школьных задач
        if (!Number.isInteger(data.precision) || data.precision < 0 || data.precision > 6) {
            fail('Знаков после запятой — целое число от 0 до 6');
        }
        template.precision = data.precision; // Например, 1 — ответ до десятых
    }

    return template; // Шаблон без id: его покажет предпросмотр или допишет в файл темы server.js
}

// Ищет случайный параметр, который влияет на ответ, но не виден в тексте условия
// (например, его забыли подставить в текст). По очереди меняем у задачи task один параметр
// на значение из другой случайной задачи: если текст от этого не изменился, а ответ
// изменился, — ученик видит одно и то же условие, а правильные ответы у него разные.
// Возвращает имя такого параметра или null
function findHiddenParam(template, task) {
    const other = generateTask(template, null); // Другая случайная задача — источник новых значений
    // Имена параметров шаблона: ["v", "t"]. Если у другой задачи значение то же самое, параметр
    // в этот раз не проверится — поэтому tryTemplate вызывает findHiddenParam для 100 задач
    for (const name of Object.keys(template.params)) {
        const params = { ...task.params }; // Копия значений задачи (... — «разворот» объекта)
        params[name] = other.params[name];  // Меняем только один параметр
        const values = computeValues(template, params); // Все величины, вместе с вычисляемыми (derived)
        // Текст и ответ считаем так же, как generateTask, — функциями fillText и computeAnswer.
        // Условие совпало с исходным, а ответ другой — значит, параметр name в тексте не виден
        if (fillText(template.text, values) === task.text && computeAnswer(template, values) !== task.answer) {
            return name; // Нашли — дальше не ищем
        }
    }
    return null; // Скрытого параметра не нашлось (null — «ничего»)
}

// Пробно создает по шаблону TRIAL_COUNT задач. Так находятся ошибки, которые видны
// только на конкретных числах: неизвестная величина в тексте, деление на ноль.
// Возвращает { examples, warnings }: несколько разных задач для предпросмотра
// и предупреждения учителю (они, в отличие от ошибок, сохранению не мешают).
// Проверка случайная: очень редкое неудачное сочетание чисел может и не попасться
function tryTemplate(template) {
    // [] — пустой список (массив). new Map() — «словарь»: по ключу (тексту условия) хранится
    // значение (ответ). let, в отличие от const, позволяет потом присвоить переменной новое значение
    const examples = [];       // Примеры для предпросмотра: [{ text, answer: "2,5" }, ...]
    const answers = new Map(); // Текст условия → ответ: у одинаковых условий ответ должен совпадать
    let rounded = null;        // Пример ответа, который пришлось округлить: { exact, answer }
    let longFraction = null;   // Пример условия с длинной дробью

    // Цикл for со счетчиком: i = 0, 1, 2, ..., 999. Перед каждым кругом проверяется i < TRIAL_COUNT,
    // после круга i++ прибавляет к i единицу
    for (let i = 0; i < TRIAL_COUNT; i++) {
        // Переменные объявлены до try: объявленные внутри фигурных скобок try после них не видны
        let task;               // Пробная задача (пока без значения — undefined)
        let exactAnswer;        // Ее точный ответ, до округления
        let hiddenParam = null; // Имя скрытого параметра, если его найдет findHiddenParam
        // try { ... } catch (error) { ... }: если внутри try возникнет ошибка (throw),
        // выполнение сразу перейдет в catch, а error — сама эта ошибка
        try {
            // Номер темы пробной задаче не нужен
            task = generateTask(template, null);
            // Точный (неокругленный) ответ — по тем же случайным значениям
            exactAnswer = evaluate(template.answer, computeValues(template, task.params));
            // Скрытый параметр ищем только в первых HIDDEN_CHECK_COUNT задачах (i от 0 до 99)
            if (i < HIDDEN_CHECK_COUNT) {
                hiddenParam = findHiddenParam(template, task);
            }
        } catch (error) {
            // Ошибки generator.js — обычные Error с понятным текстом. А SyntaxError или
            // TypeError бросает сам JavaScript, когда не может выполнить формулу
            // (например, "v *"), и их текст английский
            // Вид ошибки хранится в error.name. TypeError бывает, например, у формулы "v (t)": при v = 12
            // и t = 3 после подстановки получится "(12) (3)", и JavaScript попробует вызвать число 12 как функцию
            // «условие ? A : B» (тернарный оператор): если условие верно — A, иначе — B
            const reason = error.name === 'Error' ? error.message : 'формула записана с ошибкой — проверьте знаки и скобки';
            // Одна неудачная задача из 1000 — ошибка всего шаблона. Например, при делении на ноль:
            // «Не удалось создать задачу: Формула "v / t" дала результат Infinity»
            fail(`Не удалось создать задачу: ${reason}`);
        }

        // findHiddenParam нашел параметр, который влияет на ответ, но не виден в тексте условия
        if (hiddenParam !== null) {
            // Длинный текст ошибки разбит на две строки и склеен знаком +
            fail(`Параметр «${hiddenParam}» влияет на ответ, но не виден в тексте условия: `
                + `при одном и том же условии «${task.text}» получаются разные ответы. Подставьте его в текст`);
        }

        // Одно и то же условие с разными ответами: какая-то величина влияет на ответ,
        // но не попала в текст, — ученик не сможет решить такую задачу
        // has — есть ли такой ключ в словаре, get — значение по ключу (ответ прошлой задачи с этим условием).
        // findHiddenParam называет сам параметр, но смотрит только 100 задач, а эта проверка идет на всех 1000
        if (answers.has(task.text) && answers.get(task.text) !== task.answer) {
            // Ответы в тексте ошибки — по-русски (formatNumber): "2,5"
            fail(`Условие «${task.text}» получилось с разными ответами `
                + `(${formatNumber(answers.get(task.text))} и ${formatNumber(task.answer)}): в тексте не хватает какой-то величины`);
        }

        // В примеры берем только разные условия
        // Такого условия еще не было (в словарь оно попадет сразу после этого if), и примеров меньше EXAMPLE_COUNT
        if (!answers.has(task.text) && examples.length < EXAMPLE_COUNT) {
            // push добавляет элемент в конец списка. Ответ сразу записываем по-русски: "2,5"
            examples.push({ text: task.text, answer: formatNumber(task.answer) });
        }
        answers.set(task.text, task.answer); // set запоминает в словаре: условие → ответ

        // Округленный ответ отличается от точного — запоминаем первый такой пример для предупреждения
        if (rounded === null && exactAnswer !== task.answer) {
            rounded = { exact: exactAnswer, answer: task.answer }; // Например, { exact: 2.375, answer: 2.38 }
        }
        // Длинная дробь вроде 0,3333333333 в условии: formatNumber пишет до 10 знаков
        // По частям: \d — одна цифра, затем десятичная запятая, \d{5,} — 5 или больше цифр подряд.
        // Так "0,33333" найдется, а "2,5", "0,125" и "42 000" — нет
        if (longFraction === null && /\d,\d{5,}/.test(task.text)) {
            longFraction = task.text; // Запоминаем только первое такое условие
        }
    }

    const warnings = []; // Тексты предупреждений: constructor.js покажет каждое со словом «Внимание:»
    // Правило README: если ответ получается неточным, в условии должно быть сказано,
    // как его округлить
    // /округл/i — ищутся буквы «округл» в любом месте текста (округлите, округлить),
    // i — без учета больших и маленьких букв
    if (rounded !== null && !/округл/i.test(template.text)) {
        // В тексте предупреждения — запомненный пример: точный ответ и округленный, по-русски
        warnings.push(`Ответ не всегда получается точным: например, ${formatNumber(rounded.exact)} `
            + `округляется до ${formatNumber(rounded.answer)}. Допишите в условие, до скольких знаков `
            + 'округлить ответ (например, «Ответ округлите до десятых»), или подберите другие числа');
    }
    // size — сколько разных условий запомнено в словаре answers; 1 — все 1000 задач одинаковые
    if (answers.size === 1) {
        warnings.push('Все пробные задачи получились одинаковыми: проверьте, что в тексте есть подстановки вида {v} и что у параметров больше одного значения');
    }
    // Нашлось условие с длинной дробью — показываем его учителю целиком
    if (longFraction !== null) {
        warnings.push(`В условии получается длинная дробь: «${longFraction}». Подберите параметры так, чтобы числа в условии были «круглыми»`);
    }

    // Результат нужен предпросмотру (handlePreview в server.js). handleSaveTemplate вызывает
    // tryTemplate только ради проверки на ошибки, а примеры и предупреждения не использует
    return { examples: examples, warnings: warnings };
}

