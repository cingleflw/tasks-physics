// Обмен данными с сервером (server.js).
// Этот файл подключают обе страницы — тест (index.html и main.js) и конструктор
// (constructor.html и constructor.js), поэтому отправка запросов записана один раз.
// Файл подключается раньше main.js и constructor.js, и они могут вызывать sendRequest.
// Подключает его строка <script src="./api.js"></script> в <head> обеих страниц. Все, что объявлено
// здесь вне функций (SERVER_HINT и sendRequest), видно и коду из main.js и constructor.js

// Подсказка на случай, если связаться с сервером не удалось
// const — постоянная: значение задается один раз и потом не меняется. Имя большими буквами —
// обычай для таких постоянных. Знак + склеивает две части одной длинной строки (вторая — ниже).
// Этот текст пользователь увидит на странице, например вместо списка тем (см. showTopics в main.js)
const SERVER_HINT = "Нет связи с сервером. Запустите его командой node server.js " +
    "и откройте страницу по адресу http://localhost:8000 (см. раздел «Запуск» в README.md).";

// Отправляет запрос серверу и возвращает ответ сервера — объект из JSON.
// Без data это GET-запрос — только получить данные (например, список тем),
// с data — POST-запрос: объект data отправляется на сервер в формате JSON.
// Запрос к серверу занимает время, поэтому функция асинхронная (async):
// await ждет ответа, не замораживая страницу.
// Адрес относительный ("./api/tasks"): запрос уходит на тот же сервер, с которого открыта страница
// url — адрес на сервере, data — объект, например { id: "...", answer: "2,5" } для "./api/check".
// При вызове с одним аргументом — sendRequest('./api/topics') — data равно undefined («не задано»).
// Эту функцию вызывают main.js (showTopics, startTest, checkAnswers) и constructor.js (loadTopicList,
// createTopic, previewTask, saveTask)
async function sendRequest(url, data) {
    // Настройки запроса. Пустые настройки означают GET-запрос
    // {} — пустой объект. const не дает заменить его другим объектом, но добавлять в него поля можно
    const options = {};
    if (data !== undefined) { // !== — «не равно»: data передали, значит, это POST-запрос
        // Три настройки POST-запроса. headers — заголовки, служебные сведения о запросе. Имя поля
        // 'Content-Type' записано в кавычках: без них дефис читался бы как минус. Этот заголовок
        // обязателен: без него сервер ответит «Неверный запрос» (см. readJSON в server.js).
        // JSON.stringify превращает объект { count: 5 } в текст '{"count":5}': по сети передается текст
        options.method = 'POST';                                  // POST — отправляем данные на сервер
        options.headers = { 'Content-Type': 'application/json' }; // Сообщаем, что данные в формате JSON
        options.body = JSON.stringify(data);                      // Превращаем объект в текст JSON
    }

    // let — переменная, значение которой зададим позже. Объявляем их здесь, до try: переменная,
    // объявленная внутри фигурных скобок { }, видна только внутри них, а эти нужны и после try
    let response; // Ответ сервера: код ответа (200, 404…) и еще не прочитанный текст
    let result;   // Объект из JSON в ответе, например { topics: [ ... ] }

    // Сюда попадают ошибки связи: сервер не запущен, страница открыта двойным кликом
    // (адрес file://) или открыта с другого сервера, который отвечает не в формате JSON
    // (например, встроенный сервер WebStorm)
    try { // try — «попробуй»: при ошибке внутри остальные команды пропускаются и выполняется catch
        // fetch — встроенная функция браузера: отправляет запрос по адресу url с настройками options,
        // await ждет ответа сервера. Если ответа нет совсем (нет связи), fetch «бросает» ошибку
        // (сообщает о ней, как throw ниже) — и выполнение сразу переходит в catch.
        // Ответ с ошибкой (404, 500) — тоже ответ: его проверяет response.ok ниже
        response = await fetch(url, options);
        // Текст ответа тоже приходит не сразу, поэтому снова await. Если пришел не JSON
        // (например, HTML-страница другого сервера), json() бросит ошибку SyntaxError.
        // Ответ нашего сервера с ошибкой — тоже JSON: { error: "..." }, его поле error прочитаем ниже
        result = await response.json(); // Превращаем текст ответа обратно в объект
    } catch (error) { // Сюда переходим при ошибке в try. error — сама ошибка: нет связи или ответ не JSON
        // console.error пишет настоящую ошибку в консоль браузера — для разработчика.
        // Консоль открывается клавишей F12, на Mac — Cmd+Option+I
        console.error(error);
        // new Error(текст) создает новую ошибку (не ту error, что поймана), текст хранится в ее поле
        // message. Тот, кто вызвал sendRequest, прочитает его как error.message (см. showTopics в main.js).
        // Пользователь увидит подсказку SERVER_HINT, а не технический текст ("Failed to fetch" в Chrome).
        // Поля status у этой ошибки нет, поэтому checkAnswers в main.js не примет ее за код 400
        throw new Error(SERVER_HINT); // throw передает ошибку дальше — тому, кто вызвал sendRequest
    }

    // response.ok равно false, если сервер ответил ошибкой (например, 404 — задача не найдена).
    // Текст ошибки сервер присылает в поле error, а код ответа запоминаем в error.status:
    // по нему checkAnswers в main.js отличит «введено не число» (код 400) от остальных ошибок
    if (!response.ok) { // ! — «не»: ok равно true только для кодов ответа от 200 до 299
        // Текст ошибки — из ответа сервера, например «Введите ответ числом, например 2,5».
        // ?? берет правое значение, только если левое — null или undefined (поля error в ответе нет).
        // Эта переменная error — не та, что в catch выше: каждая видна только внутри своих { }
        const error = new Error(result.error ?? SERVER_HINT);
        error.status = response.status; // Добавляем объекту ошибки новое поле: 400, 404 или 500
        throw error;                    // Как и в catch выше: ошибку получит тот, кто вызвал sendRequest
    }
    // Сюда доходим, только если ошибок не было: throw выше сразу завершает функцию.
    // return возвращает объект из ответа, например { tasks: [ ... ] }. Его получит await
    // у вызвавшего: const test = await sendRequest(...) в startTest из main.js
    return result;
}
